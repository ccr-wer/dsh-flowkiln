/**
 * Candidate -> SKILL.md -> mounted at the DSH skills directory.
 * Default mount root: ~/.dsh/skills/<name>/SKILL.md (DSH bundle layout).
 * Dry-run by default; write only happens on explicit apply.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'

export const VERSION = '0.1.0-dsh'

export function skillsRoot() {
  return process.env.DFK_SKILLS_DIR || join(homedir(), '.dsh', 'skills')
}

const SKILL_TEMPLATE = `---
name: {name}
description: {description}
---

# {title}

Use this skill when the task matches the trigger below. Otherwise ignore it.

## When to use
{when}

## Skeleton steps
{steps}

## Variables
{variables}

## Verify
{verify}

<!--
Generated by dsh-flowkiln {version} on {generated}.
Source: {count} similar prompts clustered from local DSH history.
REVIEW BEFORE USE: this is a skeleton distilled from observed prompts, not a
vetted procedure. Fill in the real steps, fix the trigger, delete anything wrong.
-->`

export function sanitizeName(raw) {
  let name = String(raw || '')
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, '-')
    .replace(/^-+|-+$/g, '')
  name = name.replace(/-{2,}/g, '-').slice(0, 64).replace(/^-+|-+$/g, '')
  return name || 'repeated-workflow'
}

export function renderSkill(candidate) {
  // skill_name / skill_description let an LLM (or the user) override the
  // auto-derived fields; candidate.id stays the stable provenance key.
  const name = sanitizeName(candidate.skill_name || candidate.id)
  const terms = candidate.skeleton_terms || []
  const trigger = terms.slice(0, 4).join(' / ') || 'repeated task'
  const description = candidate.skill_description || (
    'Reusable workflow for repeated tasks involving ' + trigger + '. ' +
    'Use when the request matches these terms and the listed tool calls; ' +
    'do not use for unrelated one-off tasks.'
  )
  const steps = (terms.slice(0, 6).map((t, i) =>
    `${i + 1}. [TODO: describe step observed around '${t}' in the source prompts]`
  ).join('\n')) || '1. [TODO: describe the repeated operation]'
  const variables = (candidate.slots || []).join(', ') || 'none detected'
  const tools = (candidate.signatures || []).join(', ') || 'unspecified'
  const when = `Task mentions ${trigger} and would otherwise be re-explained each time.`
  const verify = `Re-run the workflow and confirm the same outcome. Observed tools: ${tools}.`
  const body = SKILL_TEMPLATE
    .replace('{name}', name)
    .replace('{description}', description.replace(/\n/g, ' ').slice(0, 1024))
    .replace('{title}', name)
    .replace('{when}', when)
    .replace('{steps}', steps)
    .replace('{variables}', variables)
    .replace('{verify}', verify)
    .replace('{version}', VERSION)
    .replace('{generated}', new Date().toISOString())
    .replace('{count}', String(candidate.count || 0))
  return { name, body }
}

/**
 * Render + optionally write a SKILL.md. Never overwrites an existing skill.
 * Returns one result record per candidate (same shape as the Codex engine).
 */
export function promote(candidates, wanted, apply, destRoot) {
  const root = destRoot || skillsRoot()
  const selected = wanted
    ? candidates.filter((c) => c.id === wanted)
    : candidates
  if (wanted && selected.length === 0) {
    return [{ error: `candidate not found: ${wanted}` }]
  }
  const results = []
  for (const candidate of selected) {
    const { name, body } = renderSkill(candidate)
    const targetDir = join(root, name)
    const targetFile = join(targetDir, 'SKILL.md')
    const record = {
      id: candidate.id,
      name,
      target: targetFile,
      applied: false,
      reason: apply ? '' : 'dry-run (pass apply:true to write)',
    }
    if (apply) {
      if (existsSync(targetFile)) {
        record.reason = 'skipped: target already exists'
      } else {
        mkdirSync(targetDir, { recursive: true })
        writeFileSync(targetFile, body, 'utf-8')
        record.applied = true
        record.reason = 'written; REVIEW before use'
      }
    }
    results.push(record)
  }
  return results
}
